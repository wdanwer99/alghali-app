// Tiny .env reader and the mapping from the root .env to each app's config.
// Only client-safe values (URL, publishable key, public DSN) ever leave the root .env.
import { existsSync, readFileSync } from 'node:fs';

/** Parses KEY=VALUE lines; ignores blanks and # comments; strips matching quotes. */
export function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (value.length >= 2 && (value[0] === '"' || value[0] === "'") && value.at(-1) === value[0]) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

export function readEnvFile(path) {
  return existsSync(path) ? parseEnv(readFileSync(path, 'utf8')) : null;
}

/** Placeholder values from .env.example count as "not set". */
export function isSet(value) {
  return Boolean(value) && !/your-|xxx|YOUR-/.test(value);
}

/** Values for one target environment ('DEV' or 'TEST'), or null when not filled in. */
export function supabaseTarget(env, target) {
  const pick = (k) => (isSet(env[`SUPABASE_${target}_${k}`]) ? env[`SUPABASE_${target}_${k}`] : '');
  const t = {
    projectRef: pick('PROJECT_REF'),
    url: pick('URL'),
    publishableKey: pick('PUBLISHABLE_KEY'),
    secretKey: pick('SECRET_KEY'),
    dbUrl: pick('DB_URL'),
  };
  return t;
}

/** What the admin (.env.local) and Flutter apps (env/dev.json) get. Never secrets. */
export function clientConfigs(env) {
  const dev = supabaseTarget(env, 'DEV');
  return {
    adminEnvLocal: [
      '# Generated by `pnpm env:sync` from the root .env — do not edit.',
      `NEXT_PUBLIC_SUPABASE_URL=${dev.url}`,
      `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${dev.publishableKey}`,
      `NEXT_PUBLIC_SENTRY_DSN=${isSet(env.NEXT_PUBLIC_SENTRY_DSN) ? env.NEXT_PUBLIC_SENTRY_DSN : ''}`,
      '',
    ].join('\n'),
    flutterDefines: {
      SUPABASE_URL: dev.url,
      SUPABASE_PUBLISHABLE_KEY: dev.publishableKey,
      SENTRY_DSN: isSet(env.SENTRY_DSN) ? env.SENTRY_DSN : '',
    },
  };
}
